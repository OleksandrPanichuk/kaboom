import { describe, expect, test } from "bun:test";

import { emptyGraph } from "../graph";
import { toDDL } from "./ddl";
import { column, index, references, table } from "./fixtures";

describe("toDDL", () => {
  test("writes tables, then foreign keys, then indexes", () => {
    const graph = {
      ...emptyGraph(),
      nodes: [
        table("users", [
          column("id", "bigint", { primaryKey: true }),
          column("email", "text", { unique: true }),
          column("manager_id", "bigint", { nullable: true }),
        ]),
        table(
          "post_tags",
          [
            column("post_id", "bigint", { primaryKey: true }),
            column("tag_id", "bigint", { primaryKey: true }),
          ],
          [index("by_tag", ["tag_id"], true)],
        ),
      ],
      edges: [
        references("users", "manager_id", "users", "id", "set-null"),
        references("post_tags", "post_id", "users", "id", "cascade"),
      ],
    };

    expect(toDDL(graph)).toBe(
      [
        'CREATE TABLE "users" (\n  "id" bigint NOT NULL,\n  "email" text NOT NULL UNIQUE,\n  "manager_id" bigint,\n  PRIMARY KEY ("id")\n);',
        'CREATE TABLE "post_tags" (\n  "post_id" bigint NOT NULL,\n  "tag_id" bigint NOT NULL,\n  PRIMARY KEY ("post_id", "tag_id")\n);',
        'ALTER TABLE "users" ADD FOREIGN KEY ("manager_id") REFERENCES "users" ("id") ON DELETE SET NULL;',
        'ALTER TABLE "post_tags" ADD FOREIGN KEY ("post_id") REFERENCES "users" ("id") ON DELETE CASCADE;',
        'CREATE UNIQUE INDEX "post_tags_tag_id_idx" ON "post_tags" ("tag_id");',
      ].join("\n\n"),
    );
  });

  test("quotes names, and writes nothing for a design without tables", () => {
    const graph = {
      ...emptyGraph(),
      nodes: [
        table('odd "name"', [column("id", "uuid", { primaryKey: true })]),
      ],
      edges: [],
    };

    expect(toDDL(graph)).toStartWith('CREATE TABLE "odd ""name"""');
    expect(toDDL(emptyGraph())).toBe("");
  });
});

describe("toDDL in each dialect", () => {
  const accounts = (groupId: string | null) => ({
    ...table(
      "accounts",
      [
        {
          ...column("id", "bigint", { primaryKey: true }),
          generated: { kind: "identity" as const, always: false },
        },
        { ...column("email", "varchar"), length: 254 },
        {
          ...column("status", "enum"),
          values: ["active", "closed"],
          default: { kind: "literal" as const, value: "active" },
        },
        {
          ...column("created_at", "timestamptz"),
          default: { kind: "now" as const },
        },
        { ...column("updated_at", "timestamptz"), onUpdate: "now" as const },
      ],
      [
        { id: "email", columns: ["email"], unique: true, lower: ["email"] },
        {
          id: "open",
          columns: ["created_at"],
          unique: false,
          where: { column: "status", op: "=" as const, value: "active" },
        },
      ],
    ),
    groupId,
  });
  const graph = (engine: "postgres" | "mysql" | "sqlite") => ({
    ...emptyGraph(),
    groups: [
      {
        id: "db",
        kind: "database" as const,
        label: "Accounts",
        parentId: null,
        engine,
      },
    ],
    nodes: [accounts("db")],
    edges: [],
  });

  test("PostgreSQL: an enum type, an identity, now() and a partial expression index", () => {
    expect(toDDL(graph("postgres"))).toBe(
      [
        "-- Accounts (PostgreSQL)",
        `CREATE TYPE "accounts_status" AS ENUM ('active', 'closed');`,
        `CREATE TABLE "accounts" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "email" varchar(254) NOT NULL,\n  "status" "accounts_status" NOT NULL DEFAULT 'active',\n  "created_at" timestamptz NOT NULL DEFAULT now(),\n  "updated_at" timestamptz NOT NULL,\n  PRIMARY KEY ("id")\n);`,
        `CREATE UNIQUE INDEX "accounts_email_idx" ON "accounts" (lower("email"));`,
        `CREATE INDEX "accounts_created_at_idx" ON "accounts" ("created_at") WHERE "status" = 'active';`,
      ].join("\n\n"),
    );
  });

  test("MySQL: an inline enum, AUTO_INCREMENT, ON UPDATE, and no partial index", () => {
    expect(toDDL(graph("mysql"))).toBe(
      [
        "-- Accounts (MySQL)",
        "CREATE TABLE `accounts` (\n  `id` bigint NOT NULL AUTO_INCREMENT,\n  `email` varchar(254) NOT NULL,\n  `status` enum('active', 'closed') NOT NULL DEFAULT 'active',\n  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,\n  `updated_at` timestamp NOT NULL ON UPDATE CURRENT_TIMESTAMP,\n  PRIMARY KEY (`id`)\n);",
        "CREATE UNIQUE INDEX `accounts_email_idx` ON `accounts` ((lower(`email`)));",
        "CREATE INDEX `accounts_created_at_idx` ON `accounts` (`created_at`);",
      ].join("\n\n"),
    );
  });

  test("SQLite: an autoincrement key, a check for the enum, and foreign keys inside the table", () => {
    const withOrders = graph("sqlite");

    withOrders.nodes.push({
      ...table("orders", [
        column("id", "integer", { primaryKey: true }),
        column("account_id", "bigint"),
      ]),
      groupId: "db",
    });
    withOrders.edges.push(
      references("orders", "account_id", "accounts", "id", "cascade") as never,
    );

    const ddl = toDDL(withOrders);

    expect(ddl).toContain(`"id" integer PRIMARY KEY AUTOINCREMENT NOT NULL,`);
    expect(ddl).toContain(
      `"status" text NOT NULL DEFAULT 'active' CHECK ("status" IN ('active', 'closed'))`,
    );
    expect(ddl).toContain(
      `  FOREIGN KEY ("account_id") REFERENCES "accounts" ("id") ON DELETE CASCADE\n);`,
    );
    expect(ddl).not.toContain("ALTER TABLE");
  });
});
